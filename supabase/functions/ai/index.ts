// Supabase Edge Function: the only place the Gemini key lives.
//   POST { action: "generate", topic, level, language, script }
//   POST { action: "analyze",  lesson_id }
// Requires a signed-in user, honours the ai_enabled switch and the per-user daily
// limit (app_settings), and saves every result so the next reader gets it for free.
import { createClient } from "npm:@supabase/supabase-js@2";
import { SYSTEM_PROMPT, buildAnalyzePrompt, buildContentPrompt } from "../_shared/prompts.ts";
import { normalizeAnalysis, normalizeContent } from "../_shared/normalizeLesson.ts";
import { LANGUAGES, parseLanguage } from "../_shared/languages.ts";

const MODEL = Deno.env.get("GEMINI_MODEL") ?? "gemini-3.5-flash";
const CORS = {
  "Access-Control-Allow-Origin": "*",
  "Access-Control-Allow-Headers": "authorization, x-client-info, apikey, content-type",
  "Access-Control-Allow-Methods": "POST, OPTIONS",
};

const admin = createClient(
  Deno.env.get("SUPABASE_URL")!,
  Deno.env.get("SUPABASE_SERVICE_ROLE_KEY")!
);

const json = (body: unknown, status = 200) =>
  new Response(JSON.stringify(body), {
    status,
    headers: { ...CORS, "Content-Type": "application/json" },
  });

async function gemini(prompt: string, maxOutputTokens: number) {
  const res = await fetch(
    `https://generativelanguage.googleapis.com/v1beta/models/${MODEL}:generateContent`,
    {
      method: "POST",
      headers: {
        "Content-Type": "application/json",
        "x-goog-api-key": Deno.env.get("GEMINI_API_KEY")!,
      },
      body: JSON.stringify({
        systemInstruction: { parts: [{ text: SYSTEM_PROMPT }] },
        contents: [{ role: "user", parts: [{ text: prompt }] }],
        generationConfig: { responseMimeType: "application/json", maxOutputTokens },
      }),
    }
  );
  const body = await res.json().catch(() => null);
  if (!res.ok) {
    console.error("gemini error", res.status, JSON.stringify(body)?.slice(0, 300));
    throw new Error(res.status === 429 ? "The AI is busy — try again shortly." : "The AI request failed.");
  }
  const parts: { text?: string; thought?: boolean }[] = body?.candidates?.[0]?.content?.parts ?? [];
  const text = parts.filter((p) => !p.thought).map((p) => p.text ?? "").join("");
  try {
    return JSON.parse(text.replace(/```json|```/g, "").trim());
  } catch {
    throw new Error("The AI reply was malformed — please try again.");
  }
}

async function setting<T>(key: string, fallback: T): Promise<T> {
  const { data } = await admin.from("app_settings").select("value").eq("key", key).maybeSingle();
  return (data?.value as T) ?? fallback;
}

/** Returns an error Response if the user may not spend an AI call. */
async function spendCall(userId: string): Promise<Response | null> {
  if ((await setting("ai_enabled", true)) === false) {
    return json({ error: "AI generation is switched off right now." }, 503);
  }
  const limit = Number(await setting("daily_limit", 10));
  const { data: ok } = await admin.rpc("consume_ai_call", { p_user: userId, p_limit: limit });
  if (!ok) {
    return json({ error: `Daily limit reached (${limit} AI requests/day). Come back tomorrow.` }, 429);
  }
  return null;
}

const topicKey = (t: string) => t.toLowerCase().replace(/\s+/g, " ").trim().slice(0, 100);

Deno.serve(async (req) => {
  if (req.method === "OPTIONS") return new Response("ok", { headers: CORS });
  if (req.method !== "POST") return json({ error: "POST only" }, 405);

  const token = req.headers.get("Authorization")?.replace(/^Bearer\s+/i, "") ?? "";
  const { data: auth } = await admin.auth.getUser(token);
  const user = auth?.user;
  if (!user) return json({ error: "Please sign in." }, 401);

  let body: Record<string, unknown>;
  try {
    body = await req.json();
  } catch {
    return json({ error: "Invalid request" }, 400);
  }

  try {
    if (body.action === "generate") {
      const topic = String(body.topic ?? "").trim().slice(0, 200);
      const language = parseLanguage(body.language);
      const script = language === "zh" && body.script === "simplified" ? "simplified" : language === "zh" ? "traditional" : null;
      const level = String(body.level ?? "");
      if (!topic || !LANGUAGES[language].levels.includes(level)) {
        return json({ error: "Topic and valid level required" }, 400);
      }
      const key = topicKey(topic);

      // 1. already generated by someone? serve it instantly, free.
      let q = admin.from("lessons").select("*").eq("visibility", "shared")
        .eq("language", language).eq("level", level).eq("topic_key", key);
      q = script ? q.eq("script", script) : q.is("script", null);
      const { data: hit } = await q.maybeSingle();
      if (hit) return json({ lesson: hit, cached: true });

      // 2. otherwise pay for one AI call and save it for everyone
      const blocked = await spendCall(user.id);
      if (blocked) return blocked;
      const raw = await gemini(buildContentPrompt(topic, level, language, script ?? "traditional"), 2000);
      const lesson = normalizeContent(raw, level, language, script ?? "traditional");
      if (!lesson) return json({ error: "The model returned an incomplete reading — try again." }, 502);

      const row = {
        visibility: "shared", owner: null, language, script, level, topic_key: key,
        title: lesson.title, category: lesson.category, duration: lesson.duration,
        content: lesson.content, analysis: "none",
      };
      const ins = await admin.from("lessons").insert(row).select("*").single();
      if (ins.error) {
        // lost a race with an identical request: return the winner
        let q2 = admin.from("lessons").select("*").eq("visibility", "shared")
          .eq("language", language).eq("level", level).eq("topic_key", key);
        q2 = script ? q2.eq("script", script) : q2.is("script", null);
        const { data: winner } = await q2.maybeSingle();
        if (winner) return json({ lesson: winner, cached: true });
        console.error("insert failed", ins.error);
        return json({ error: "Could not save the reading." }, 500);
      }
      return json({ lesson: ins.data, cached: false });
    }

    if (body.action === "analyze") {
      const { data: lesson } = await admin.from("lessons").select("*").eq("id", String(body.lesson_id ?? "")).maybeSingle();
      if (!lesson || (lesson.visibility !== "shared" && lesson.owner !== user.id)) {
        return json({ error: "Reading not found." }, 404);
      }
      if (lesson.analysis === "ready") return json({ lesson, cached: true });

      const blocked = await spendCall(user.id);
      if (blocked) return blocked;
      const raw = await gemini(
        buildAnalyzePrompt(String(lesson.content).slice(0, 6000), lesson.level, parseLanguage(lesson.language)),
        8192
      );
      const analysis = normalizeAnalysis(raw);
      if (!analysis) return json({ error: "The analysis was incomplete — try again." }, 502);

      const upd = await admin.from("lessons").update({
        translation: analysis.translation, vocabulary: analysis.vocabulary,
        glossary: analysis.glossary ?? [], grammar: analysis.grammar,
        questions: analysis.questions, analysis: "ready",
      }).eq("id", lesson.id).select("*").single();
      if (upd.error) {
        console.error("update failed", upd.error);
        return json({ error: "Could not save the analysis." }, 500);
      }
      return json({ lesson: upd.data, cached: false });
    }

    return json({ error: "Unknown action" }, 400);
  } catch (e) {
    console.error(e);
    return json({ error: e instanceof Error ? e.message : "Something went wrong" }, 502);
  }
});
